"""Deterministic evaluation report writer (spec section 15).

``ReportWriter.write`` persists a full run directory:

- ``resolved_config.yaml`` — the resolved experiment config.
- ``metrics.json`` — overall Re-ID metrics.
- ``metrics_by_slice.csv`` — per condition-slice metrics (pandas).
- ``degradation_curves.csv`` — per arm/bin accuracy + chance-normalized.
- ``degradation_slopes.json`` — per arm slope/AUC/CI.
- ``bootstrap_intervals.json`` — bootstrap CI artifacts.
- ``report.md`` — human-readable summary generated by deterministic rules
  only (no LLM): dataset/split, checkpoints, metrics with CI, paired
  differences vs Arm A, blackout results, degradation slopes, per-bin
  advantages, a mandatory limitations statement, and a conclusion chosen
  from four evidence-grounded templates.
"""
from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Mapping

import numpy as np
import pandas as pd
import yaml

from evaluation.degradation import DegradationResult

LIMITATIONS = [
    "This evaluation is vision-only Phase 1.",
    "There is no AIS/radar fusion in fair comparison.",
    "Note: gap durations may be frame-count estimates.",
]


class ReportWriter:
    """Write a deterministic evaluation report into ``run_dir``."""

    def __init__(self, run_dir: Path) -> None:
        self.run_dir = Path(run_dir)

    # ------------------------------------------------------------------ API
    def write(
        self,
        config: dict,
        metrics: dict,                          # overall Re-ID metrics
        metrics_by_slice: dict[str, dict],      # condition slice -> metrics
        degradation_results: list[DegradationResult],
        blackout_results: dict | None = None,   # from BlackoutHarness.evaluate_arm
        bootstrap_intervals: dict | None = None,
        git_state: dict | None = None,
    ) -> None:
        self.run_dir.mkdir(parents=True, exist_ok=True)
        self._write_config(config)
        self._write_json("metrics.json", metrics)
        self._write_slices(metrics_by_slice)
        self._write_degradation(degradation_results)
        self._write_json("bootstrap_intervals.json", bootstrap_intervals or {})
        md = self._report_md(
            config,
            metrics,
            metrics_by_slice,
            degradation_results,
            blackout_results,
            bootstrap_intervals,
            git_state,
        )
        (self.run_dir / "report.md").write_text(md, encoding="utf-8")

    # ------------------------------------------------------------- file I/O
    def _write_config(self, config: dict) -> None:
        (self.run_dir / "resolved_config.yaml").write_text(
            yaml.dump(config, sort_keys=False, default_flow_style=False),
            encoding="utf-8",
        )

    def _write_json(self, name: str, payload: Any) -> None:
        # no sort_keys: metric dicts mix str ("mAP") and int (rank) keys.
        (self.run_dir / name).write_text(
            json.dumps(payload, indent=2, default=_json_default),
            encoding="utf-8",
        )

    def _write_slices(self, metrics_by_slice: dict[str, dict]) -> None:
        if not metrics_by_slice:
            (self.run_dir / "metrics_by_slice.csv").write_text("", encoding="utf-8")
            return
        df = pd.DataFrame.from_dict(metrics_by_slice, orient="index")
        df.index.name = "slice"
        df.to_csv(self.run_dir / "metrics_by_slice.csv")

    def _write_degradation(self, results: list[DegradationResult]) -> None:
        rows = [
            {
                "arm_name": r.arm_name,
                "bin_label": label,
                "accuracy": acc,
                "chance_normalized": cn,
            }
            for r in results
            for label, acc, cn in zip(r.bin_labels, r.accuracies, r.chance_normalized)
        ]
        pd.DataFrame(rows).to_csv(self.run_dir / "degradation_curves.csv", index=False)
        slopes = {
            r.arm_name: {
                "slope": r.slope,
                "auc": r.auc,
                "ci_lower": r.ci_lower,
                "ci_upper": r.ci_upper,
                "bin_labels": r.bin_labels,
                "accuracies": r.accuracies,
                "chance_normalized": r.chance_normalized,
            }
            for r in results
        }
        self._write_json("degradation_slopes.json", slopes)

    # ------------------------------------------------------------ report.md
    def _report_md(
        self,
        config: dict,
        metrics: dict,
        metrics_by_slice: dict[str, dict],
        degradation_results: list[DegradationResult],
        blackout_results: dict | None,
        bootstrap_intervals: dict | None,
        git_state: dict | None,
    ) -> str:
        lines: list[str] = []
        lines.append("# Maritime Vessel Re-ID — Evaluation Report")
        lines.append("")
        lines.append(self._section_dataset(config))
        lines.append("")
        lines.append(self._section_checkpoints(config))
        lines.append("")
        lines.append(self._section_overall(metrics, bootstrap_intervals))
        lines.append("")
        lines.append(self._section_paired(bootstrap_intervals))
        lines.append("")
        lines.append(self._section_blackout(blackout_results))
        lines.append("")
        lines.append(self._section_degradation(degradation_results))
        lines.append("")
        lines.append(self._section_limitations())
        lines.append("")
        lines.append(self._section_conclusion(metrics, degradation_results))
        if git_state:
            lines.append("")
            lines.append("## Git state")
            lines.append("")
            lines.append(f"```\n{json.dumps(git_state, indent=2, default=_json_default)}\n```")
        return "\n".join(lines)

    @staticmethod
    def _section_dataset(config: dict) -> str:
        dataset = config.get("dataset", config.get("data", "unknown"))
        if isinstance(dataset, Mapping):
            name = dataset.get("name", dataset.get("path", "unknown"))
        else:
            name = dataset
        split = config.get("split", "unknown")
        return (
            "## Dataset & split\n\n"
            f"- Dataset: `{name}`\n"
            f"- Split: `{split}`"
        )

    @staticmethod
    def _section_checkpoints(config: dict) -> str:
        ckpt = config.get("checkpoints", config.get("model", {}))
        if isinstance(ckpt, Mapping):
            items = "\n".join(f"- {k}: `{v}`" for k, v in ckpt.items()) or "- none"
            return f"## Model checkpoints\n\n{items}"
        return f"## Model checkpoints\n\n- `{ckpt}`"

    @staticmethod
    def _section_overall(metrics: dict, bootstrap_intervals: dict | None) -> str:
        lines = ["## Overall metrics with CI", ""]
        if metrics:
            lines.append("- mAP: " + _fmt(metrics.get("mAP")))
            lines.append("- Rank-1: " + _fmt(metrics.get(1)))
            lines.append("- Rank-5: " + _fmt(metrics.get(5)))
            lines.append("- Rank-10: " + _fmt(metrics.get(10)))
        ci = _ci_from_intervals(bootstrap_intervals)
        if ci is not None:
            lines.append(f"- Bootstrap CI (mean): {_fmt(ci[0])} [{_fmt(ci[1])}, {_fmt(ci[2])}]")
        return "\n".join(lines) if len(lines) > 2 else "## Overall metrics with CI\n\n- (no metrics provided)"

    @staticmethod
    def _section_paired(bootstrap_intervals: dict | None) -> str:
        lines = ["## Paired differences vs Arm A", ""]
        if not bootstrap_intervals:
            lines.append("- (none provided)")
            return "\n".join(lines)
        for key, value in sorted(bootstrap_intervals.items()):
            lines.append(f"- {key}: {json.dumps(value, default=_json_default)}")
        return "\n".join(lines)

    @staticmethod
    def _section_blackout(blackout_results: dict | None) -> str:
        lines = ["## Blackout results per duration bin", ""]
        if not blackout_results:
            lines.append("- (none provided)")
            return "\n".join(lines)
        for duration in sorted(blackout_results, key=lambda d: float(d)):
            row = blackout_results[duration]
            lines.append(
                f"- {duration}s: top-1={_fmt(row.get('top1'))}, "
                f"top-5={_fmt(row.get('top5'))}, n={row.get('num_episodes', '?')}"
            )
        return "\n".join(lines)

    @staticmethod
    def _section_degradation(results: list[DegradationResult]) -> str:
        lines = ["## Degradation slopes + per-bin advantages", ""]
        if not results:
            lines.append("- (none provided)")
            return "\n".join(lines)
        for r in results:
            lines.append(
                f"- Arm `{r.arm_name}`: slope={_fmt(r.slope)}, auc={_fmt(r.auc)}, "
                f"CI=[{_fmt(r.ci_lower)}, {_fmt(r.ci_upper)}]"
            )
            lines.append(
                "  - "
                + ", ".join(
                    f"{label}: acc={_fmt(acc)} (chance-norm {_fmt(cn)})"
                    for label, acc, cn in zip(r.bin_labels, r.accuracies, r.chance_normalized)
                )
            )
        if len(results) >= 2:
            bins = {label for r in results for label in r.bin_labels}
            for label in sorted(bins):
                best = max(results, key=lambda r: _bin_acc(r, label))
                lines.append(
                    f"- Bin `{label}` advantage: Arm `{best.arm_name}` "
                    f"(acc={_fmt(_bin_acc(best, label))})"
                )
        return "\n".join(lines)

    @staticmethod
    def _section_limitations() -> str:
        lines = ["## Limitations", ""]
        lines.extend(f"- {text}" for text in LIMITATIONS)
        return "\n".join(lines)

    @staticmethod
    def _section_conclusion(metrics: dict, results: list[DegradationResult]) -> str:
        mAP = metrics.get("mAP") if metrics else None
        slopes = [r.slope for r in results if not math.isnan(r.slope)]
        template = _conclusion_template(mAP, slopes)
        return "## Conclusion\n\n" + template


def _bin_acc(result: DegradationResult, label: str) -> float:
    if label not in result.bin_labels:
        return -math.inf
    return result.accuracies[result.bin_labels.index(label)]


def _fmt(value: Any) -> str:
    if value is None:
        return "n/a"
    f = float(value)
    if math.isnan(f) or math.isinf(f):
        return "n/a"
    return f"{f:.3f}"


def _ci_from_intervals(bootstrap_intervals: dict | None):
    """Extract a (mean, lo, hi) triple from bootstrap_intervals if present."""
    if not bootstrap_intervals:
        return None
    cand = bootstrap_intervals.get("overall") or bootstrap_intervals.get("bootstrap_ci")
    if isinstance(cand, Mapping):
        keys = {"mean", "ci_low", "ci_high"} & set(cand)
        if keys == {"mean", "ci_low", "ci_high"}:
            return cand["mean"], cand["ci_low"], cand["ci_high"]
        if keys == {"mean", "ci_lower", "ci_upper"}:
            return cand["mean"], cand["ci_lower"], cand["ci_upper"]
    return None


def _conclusion_template(mAP: float | None, slopes: list[float]) -> str:
    """Pick one of four evidence-grounded templates.

    Rules (deterministic):
    - positive: mAP >= 0.6 and the mean degradation slope is mild (>= -0.3).
    - negative: mAP is available and < 0.3.
    - gap-regime: strong accuracy but steep degradation (mean slope < -0.5),
      i.e. only short gaps are handled well.
    - mixed: anything else (including missing mAP).
    """
    mean_slope = float(np.mean(slopes)) if slopes else None
    if mAP is not None and mAP >= 0.6 and (mean_slope is None or mean_slope >= -0.3):
        return (
            "The evaluated arm maintains strong re-identification accuracy across "
            "gap durations with mild degradation; the approach is ready to advance "
            "to the next phase."
        )
    if mAP is not None and mAP < 0.3:
        return (
            "The evaluated arm does not meet the accuracy bar; the approach should "
            "be reworked before the next phase."
        )
    if mAP is not None and mean_slope is not None and mean_slope < -0.5:
        return (
            "Accuracy degrades steeply with gap duration: the approach is only "
            "reliable in the short-gap regime, and long-gap robustness needs "
            "dedicated work."
        )
    return (
        "The evaluated arm shows competitive accuracy on short gaps but mixed "
        "results across longer gaps; further analysis is required before the "
        "next phase."
    )


def _json_default(value: Any) -> Any:
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return float(value)
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (np.bool_,)):
        return bool(value)
    return str(value)
